        if isempty(values)
            return;
        end

        lo=min(values);
        hi=max(values);

        if hi<=lo

            lo=lo-1;
            hi=hi+1;
        end

        lo=...
            floor(...
                (lo-margin)/5)*5;

        hi=...
            ceil(...
                (hi+margin)/5)*5;

        if hi<=lo
            hi=lo+10;
        end

        ylim(...
            ax,...
            [lo hi]);
    end

%% History

    function trimHistory()

        cutoff=...
            elapsedTime()-...
            HISTORY_S;

        [state.legT,...
         state.legV]=...
            trimPair(...
                state.legT,...
                state.legV,...
                cutoff);

        [state.motorT,...
         state.motorV]=...
            trimPair(...
                state.motorT,...
                state.motorV,...
                cutoff);

        [state.angleSmoothT,...
         state.angleSmoothV]=...
            trimPair(...
                state.angleSmoothT,...
                state.angleSmoothV,...
                cutoff);

        if ~isempty(state.heelT)

            state.heelT=...
                state.heelT(...
                    state.heelT>=cutoff);
        end
    end

    function [t,v]=...
            trimPair(...
                t,...
                v,...
                cutoff)

        if isempty(t)
            return;
        end

        keep=...
            t>=cutoff;

        t=t(keep);
        v=v(keep);
    end

