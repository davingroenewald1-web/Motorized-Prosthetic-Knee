%% Save

    function saveSession(~,~)

        if isempty(state.legT) && ...
           isempty(state.motorT)

            uialert(...
                fig,...
                'There is no session data to save yet.',...
                'Nothing to save');

            return;
        end

        [file,path]=uiputfile(...
            '*.csv',...
            'Save session CSV',...
            'knee_session_raw.csv');

        if isequal(file,0)
            return;
        end

        rawFile=...
            fullfile(...
                path,...
                file);

        device=[...
            repmat(...
                "Leader",...
                numel(state.legT),...
                1);...
            repmat(...
                "Motor",...
                numel(state.motorT),...
                1)];

        time_s=[...
            state.legT(:);...
            state.motorT(:)];

        angle_deg=[...
            state.legV(:);...
            state.motorV(:)];

        rawTable=table(...
            device,...
            time_s,...
            angle_deg,...
            'VariableNames',...
            {...
            'Device',...
            'Time_s',...
            'Angle_deg'});

        rawTable=...
            sortrows(...
                rawTable,...
                'Time_s');

        writetable(...
            rawTable,...
            rawFile);

        [folder,...
         base,...
         ~]=...
            fileparts(rawFile);

        if ~isempty(state.cycles)

            pct=...
                linspace(...
                    0,...
                    100,...
                    GAIT_POINTS).';

            legAvg=mean(...
                vertcat(...
                    state.cycles.leg),...
                1,...
                'omitnan').';

            motorRows={};

            for ii=1:numel(state.cycles)

                if ~isempty(...
                    state.cycles(ii).motor)

                    motorRows{end+1}=...
                        state.cycles(ii).motor; %#ok<AGROW>
                end
            end

            if isempty(motorRows)

                motorAvg=...
                    NaN(size(pct));

            else

                motorAvg=mean(...
                    vertcat(...
                        motorRows{:}),...
                    1,...
                    'omitnan').';
            end

            gaitFile=...
                fullfile(...
                    folder,...
                    [base '_average_gait.csv']);

            gaitTable=table(...
                pct,...
                legAvg,...
                motorAvg,...
                'VariableNames',...
                {...
                'GaitPercent',...
                'LeaderAvg_deg',...
                'MotorAvg_deg'});

            writetable(...
                gaitTable,...
                gaitFile);
        end

        setStatus(...
            "CSV files saved to "+...
            string(folder));
    end

