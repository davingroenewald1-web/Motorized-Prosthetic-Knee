    function connectLeader()

        btnLeader.Enable='off';
        btnLeader.Text='Connecting...';

        setStatus(...
            "Opening TCP connection to "+...
            LEADER_HOST+" ...");

        try
            % Remove any previous client object
            state.ws=[];
            state.wsConnected=false;
            state.wsBuffer=uint8([]);
            state.wsFragment=uint8([]);
            state.wsFragmentOpcode=uint8(0);

            pause(0.05);

            % -------------------------------------------------
            % TCP CONNECTION
            % -------------------------------------------------

            state.ws=tcpclient(...
                LEADER_HOST,...
                LEADER_PORT,...
                'Timeout',...
                WS_CONNECT_TIMEOUT_S);

            setStatus(...
                "TCP connected — starting WebSocket handshake...");

            pause(0.05);

            % -------------------------------------------------
            % CREATE WEBSOCKET KEY
            % -------------------------------------------------

            keyBytes=uint8(...
                randi(...
                    [0 255],...
                    1,...
                    16));

            wsKey=string(...
                matlab.net.base64encode(...
                    keyBytes));

            % -------------------------------------------------
            % WEBSOCKET HANDSHAKE REQUEST
            % -------------------------------------------------

            request=...
                "GET "+LEADER_PATH+" HTTP/1.1"+sprintf('\r\n')+...
                "Host: "+LEADER_HOST+":"+string(LEADER_PORT)+sprintf('\r\n')+...
                "Upgrade: websocket"+sprintf('\r\n')+...
                "Connection: Upgrade"+sprintf('\r\n')+...
                "Sec-WebSocket-Key: "+wsKey+sprintf('\r\n')+...
                "Sec-WebSocket-Version: 13"+sprintf('\r\n')+...
                "Origin: http://"+LEADER_HOST+sprintf('\r\n')+...
                sprintf('\r\n');

            requestBytes=uint8(...
                unicode2native(...
                    char(request),...
                    'UTF-8'));

            write(...
                state.ws,...
                requestBytes,...
                'uint8');

            % -------------------------------------------------
            % WAIT FOR SERVER HANDSHAKE
            % -------------------------------------------------

            responseBytes=uint8([]);

            waitTimer=tic;
            headerEnd=[];

            while toc(waitTimer)<WS_HANDSHAKE_TIMEOUT_S

                if isempty(state.ws)
                    error(...
                        'TCP connection disappeared during handshake.');
                end

                n=state.ws.NumBytesAvailable;

                if n>0

                    newBytes=read(...
                        state.ws,...
                        n,...
                        'uint8');

                    responseBytes=[...
                        responseBytes,...
                        reshape(...
                            uint8(newBytes),...
                            1,...
                            [])]; %#ok<AGROW>

                    headerEnd=...
                        findHeaderEnd(...
                            responseBytes);

                    if ~isempty(headerEnd)
                        break;
                    end
                end

                pause(0.01);
                drawnow limitrate;
            end

            if isempty(headerEnd)

                error(...
                    ['TCP connection opened, but the ESP32 did not '...
                     'return a WebSocket handshake response.']);
            end

            % -------------------------------------------------
            % PARSE HANDSHAKE
            % -------------------------------------------------

            headerChars=native2unicode(...
                responseBytes(1:headerEnd),...
                'UTF-8');

            headerText=string(headerChars);

            valid101=...
                contains(...
                    headerText,...
                    "HTTP/1.1 101",...
                    'IgnoreCase',true) || ...
                contains(...
                    headerText,...
                    "HTTP/1.0 101",...
                    'IgnoreCase',true) || ...
                contains(...
                    headerText,...
                    "101 Switching Protocols",...
                    'IgnoreCase',true);

            if ~valid101

                error(...
                    "ESP32 WebSocket handshake failed. Response: "+...
                    headerText);
            end

            % Anything received after the HTTP header is already
            % WebSocket data.
            if headerEnd<numel(responseBytes)

                state.wsBuffer=...
                    responseBytes(...
                        headerEnd+1:end);

            else

                state.wsBuffer=uint8([]);
            end

            state.wsConnected=true;

            btnLeader.Text=...
                'Disconnect system';

            btnLeader.BackgroundColor=...
                [0.22 0.48 0.32];

            setStatus(...
                "Connected to leader ESP32 — waiting for telemetry.");

            % Parse any WebSocket bytes that arrived together with
            % the handshake response.
            if ~isempty(state.wsBuffer)

                tmp=state.wsBuffer;

                state.wsBuffer=uint8([]);

                parseWebSocketBytes(tmp);
            end

        catch ME

            state.wsConnected=false;
            state.ws=[];
            state.wsBuffer=uint8([]);
            state.wsFragment=uint8([]);
            state.wsFragmentOpcode=uint8(0);

            btnLeader.Text=...
                'Connect system';

            btnLeader.BackgroundColor=...
                [0.94 0.94 0.94];

            setStatus(...
                "System connection failed: "+...
                string(ME.message));

            uialert(...
                fig,...
                sprintf([...
                'Could not connect to the leader ESP32.\n\n'...
                'MATLAB ERROR:\n%s\n\n'...
                'Check the following:\n'...
                '1. Windows is connected to KNEE_LEADER_WIFI.\n'...
                '2. The leader terminal says WIFI ACCESS POINT STARTED.\n'...
                '3. The leader terminal says WebSocket server ready.\n'...
                '4. The ESP32 address is 192.168.4.1.\n'...
                '5. Restart the MATLAB app after reconnecting WiFi.'],...
                ME.message),...
                'System connection failed');
        end

        btnLeader.Enable='on';
    end

    function idx=findHeaderEnd(bytes)

        idx=[];

        target=uint8(...
            [13 10 13 10]);

        if numel(bytes)<4
            return;
        end

        for ii=1:(numel(bytes)-3)

            if all(...
                bytes(ii:ii+3)==target)

                idx=ii+3;
                return;
            end
        end
    end

