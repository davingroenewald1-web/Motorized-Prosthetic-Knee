%% Main service

    function appTick(~,~)

        if ~isvalid(fig)
            return;
        end

        if state.wsConnected && ~isempty(state.ws)

            try
                n=state.ws.NumBytesAvailable;

                if n>0

                    bytes=read(...
                        state.ws,...
                        n,...
                        'uint8');

                    parseWebSocketBytes(...
                        uint8(bytes));
                end

            catch ME

                setStatus(...
                    "System connection lost: "+...
                    string(ME.message));

                disconnectLeader(true);
            end
        end

        if state.demoRunning

            tNow=elapsedTime();

            if (tNow-state.lastDemoT)>=...
                    DEMO_SAMPLE_PERIOD_S

                state.lastDemoT=tNow;

                generateDemoSample(tNow);
            end
        end

        tNow=elapsedTime();

        if (tNow-state.lastPlotT)>=...
                PLOT_PERIOD_S

            state.lastPlotT=tNow;

            updatePlotsAndReadouts();
        end
    end

    function timerError(~,evt)

        try
            setStatus(...
                "Timer error: "+...
                string(evt.Data.Message));
        catch
            setStatus("Timer error.");
        end
    end

