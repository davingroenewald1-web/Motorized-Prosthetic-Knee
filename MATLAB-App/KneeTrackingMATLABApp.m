    function generateDemoSample(t)

        phase=...
            mod(...
                t,...
                DEMO_CYCLE_S)/...
            DEMO_CYCLE_S;

        pct=...
            phase*100;

        leader=...
            demoKneeCurve(pct)+...
            0.25*randn();

        motorPct=...
            mod(...
                pct-3,...
                100);

        motor=...
            0.97*...
            demoKneeCurve(...
                motorPct)+...
            0.35*randn();

        onTelemetrySample(...
            leader,...
            motor,...
            true);
    end

    function y=demoKneeCurve(pct)

        loading=...
            14*...
            exp(...
                -((pct-15)/7).^2);

        swing=...
            55*...
            exp(...
                -((pct-72)/11).^2);

        extensionDip=...
            6*...
            exp(...
                -(min(...
                    pct,...
                    100-pct)/4).^2);

        y=max(...
            0,...
            6-...
            extensionDip+...
            loading+...
            swing);
    end

