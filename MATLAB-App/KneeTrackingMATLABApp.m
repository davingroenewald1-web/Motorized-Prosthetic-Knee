%% Processed gait plot

    function updateGaitPlot(nowT)

        pct=linspace(...
            0,...
            100,...
            GAIT_POINTS);

        % Completed gait averages
        if isempty(state.cycles)

            gaitLegLine.XData=NaN;
            gaitLegLine.YData=NaN;

            gaitMotorLine.XData=NaN;
            gaitMotorLine.YData=NaN;

        else

            legMatrix=...
                vertcat(...
                    state.cycles.leg);

            legAverage=mean(...
                legMatrix,...
                1,...
                'omitnan');

            legAverage=...
                smoothGaitCurve(...
                    legAverage,...
                    GAIT_SMOOTH_WINDOW);

            gaitLegLine.XData=pct;
            gaitLegLine.YData=legAverage;

            motorRows={};

            for ii=1:numel(state.cycles)

                if ~isempty(...
                    state.cycles(ii).motor)

                    motorRows{end+1}=...
                        state.cycles(ii).motor; %#ok<AGROW>
                end
            end

            if ~isempty(motorRows)

                motorAverage=mean(...
                    vertcat(...
                        motorRows{:}),...
                    1,...
                    'omitnan');

                motorAverage=...
                    smoothGaitCurve(...
                        motorAverage,...
                        GAIT_SMOOTH_WINDOW);

                gaitMotorLine.XData=pct;
                gaitMotorLine.YData=motorAverage;

            else

                gaitMotorLine.XData=NaN;
                gaitMotorLine.YData=NaN;
            end
        end

        % Live gait
        if state.walkingActive && ...
           isfinite(state.cycleStartT)

            elapsed=...
                nowT-...
                state.cycleStartT;

            if ~isempty(...
                    state.cycleDurations)

                expectedCycle=...
                    median(...
                        state.cycleDurations);

            else

                expectedCycle=...
                    DEFAULT_CYCLE_S;
            end

            expectedCycle=max(...
                MIN_CYCLE_S,...
                min(...
                    MAX_CYCLE_S,...
                    expectedCycle));

            displayDuration=max(...
                expectedCycle,...
                elapsed/0.95);

            if displayDuration<=0
                displayDuration=DEFAULT_CYCLE_S;
            end

            % Leader live
            legMask=...
                state.legT>=state.cycleStartT & ...
                state.legT<=nowT;

            if nnz(legMask)>=2

                tPart=...
                    state.legT(legMask);

                legPart=...
                    state.legV(legMask);

                xPct=...
                    100*...
                    (tPart-state.cycleStartT)/...
                    displayDuration;

                nBase=min(...
                    3,...
                    numel(legPart));

                legBase=mean(...
                    legPart(1:nBase),...
                    'omitnan');

                legPart=...
                    legPart-...
                    legBase;

                legPart=...
                    smoothGaitCurve(...
                        legPart,...
                        min(...
                            5,...
                            numel(legPart)));

                gaitLiveLegLine.XData=xPct;
                gaitLiveLegLine.YData=legPart;

            else

                gaitLiveLegLine.XData=NaN;
                gaitLiveLegLine.YData=NaN;
            end

            % Motor live
            motorMask=...
                state.motorT>=state.cycleStartT & ...
                state.motorT<=nowT;

            if nnz(motorMask)>=2

                tMotor=...
                    state.motorT(motorMask);

                motorPart=...
                    state.motorV(motorMask);

                xMotor=...
                    100*...
                    (tMotor-state.cycleStartT)/...
                    displayDuration;

                nBase=min(...
                    3,...
                    numel(motorPart));

                motorBase=mean(...
                    motorPart(1:nBase),...
                    'omitnan');

                motorPart=...
                    motorPart-...
                    motorBase;

                motorPart=...
                    smoothGaitCurve(...
                        motorPart,...
                        min(...
                            5,...
                            numel(motorPart)));

                gaitLiveMotorLine.XData=xMotor;
                gaitLiveMotorLine.YData=motorPart;

            else

                gaitLiveMotorLine.XData=NaN;
                gaitLiveMotorLine.YData=NaN;
            end

        else

            gaitLiveLegLine.XData=NaN;
            gaitLiveLegLine.YData=NaN;

            gaitLiveMotorLine.XData=NaN;
            gaitLiveMotorLine.YData=NaN;
        end

        allY=[...
            gaitLegLine.YData,...
            gaitMotorLine.YData,...
            gaitLiveLegLine.YData,...
            gaitLiveMotorLine.YData];

        allY=...
            allY(...
                isfinite(allY));

        if ~isempty(allY)

            lo=min(...
                -5,...
                floor(...
                    (min(allY)-2)/5)*5);

            hi=max(...
                75,...
                ceil(...
                    (max(allY)+5)/5)*5);

            if hi<=lo
                hi=lo+10;
            end

            ylim(...
                axGait,...
                [lo hi]);

        else

            ylim(...
                axGait,...
                [-5 75]);
        end
    end

    %% Delay for the completed displayed gait graph
    function updateDisplayedDelay()
        state.delayMs=NaN;
        state.delayCorr=NaN;

        delayText.String='Peak delay: waiting for completed cycle';
        delayText.Color=[1.00 0.82 0.40];

        delayLeaderCursor.XData=[NaN NaN];
        delayLeaderCursor.YData=[NaN NaN];
        delayMotorCursor.XData=[NaN NaN];
        delayMotorCursor.YData=[NaN NaN];
        delaySpanLine.XData=[NaN NaN];
        delaySpanLine.YData=[NaN NaN];
        delayLeaderMarker.XData=NaN;
        delayLeaderMarker.YData=NaN;
        delayMotorMarker.XData=NaN;
        delayMotorMarker.YData=NaN;

        if isempty(state.cycles)
            return;
        end

        xLeg=gaitLegLine.XData;
        yLeg=gaitLegLine.YData;
        xMotor=gaitMotorLine.XData;
        yMotor=gaitMotorLine.YData;

        if isempty(xLeg) || isempty(yLeg) || isempty(xMotor) || isempty(yMotor)
            return;
        end

        validLeg=isfinite(xLeg) & isfinite(yLeg);
        validMotor=isfinite(xMotor) & isfinite(yMotor);

        if nnz(validLeg)<5 || nnz(validMotor)<5
            return;
        end

        xLeg=xLeg(validLeg);
        yLeg=yLeg(validLeg);
        xMotor=xMotor(validMotor);
        yMotor=yMotor(validMotor);

        if (max(yLeg)-min(yLeg))<DELAY_MIN_DISPLAY_ROM_DEG || ...
           (max(yMotor)-min(yMotor))<DELAY_MIN_DISPLAY_ROM_DEG
            delayText.String='Peak delay: move knee to measure';
            return;
        end

        [leaderPeakY,idxLegPeak]=max(yLeg);
        [motorPeakY,idxMotorPeak]=max(yMotor);

        leaderPeakX=xLeg(idxLegPeak);
        motorPeakX=xMotor(idxMotorPeak);

        durations=arrayfun(@(c) c.t1-c.t0, state.cycles);
        durations=durations(isfinite(durations) & durations>0);
        if isempty(durations)
            return;
        end

        displayCycleS=median(durations);
        state.delayMs=(motorPeakX-leaderPeakX)*displayCycleS*10.0;

        cmat=corrcoef(yLeg(:),yMotor(:),'Rows','complete');
        if isequal(size(cmat),[2 2])
            state.delayCorr=cmat(1,2);
        else
            state.delayCorr=NaN;
        end

        yLim=ylim(axGait);
        ySpan=yLim(2)-0.10*(yLim(2)-yLim(1));

        delayLeaderCursor.XData=[leaderPeakX leaderPeakX];
        delayLeaderCursor.YData=yLim;
        delayMotorCursor.XData=[motorPeakX motorPeakX];
        delayMotorCursor.YData=yLim;
        delaySpanLine.XData=[leaderPeakX motorPeakX];
        delaySpanLine.YData=[ySpan ySpan];
        delayLeaderMarker.XData=leaderPeakX;
        delayLeaderMarker.YData=leaderPeakY;
        delayMotorMarker.XData=motorPeakX;
        delayMotorMarker.YData=motorPeakY;

        delayText.String=sprintf('Peak delay: %+.0f ms',state.delayMs);
        delayText.Color=[0.45 0.95 0.67];
    end

