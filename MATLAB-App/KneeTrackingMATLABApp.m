%% Tracking accuracy

    function updateAccuracy()

        nowT=elapsedTime();

        motorFresh=...
            isfinite(state.motorAngle) && ...
            ~isempty(state.motorT) && ...
            (nowT-state.motorT(end))<=...
            MOTOR_STALE_S;

        if ~motorFresh || ...
           numel(state.legT)<2 || ...
           numel(state.motorT)<2

            valAcc.Text='– %';

            valAcc.FontColor=...
                [0.92 0.95 0.97];

            return;
        end

        cutoff=...
            nowT-...
            ACCURACY_WINDOW_S;

        % Motor and leader now arrive in the same WebSocket
        % telemetry sample, so their timestamps normally match.
        [tCommon,...
         idxLeg,...
         idxMotor]=...
            intersect(...
                state.legT,...
                state.motorT,...
                'stable');

        keep=...
            tCommon>=cutoff;

        idxLeg=...
            idxLeg(keep);

        idxMotor=...
            idxMotor(keep);

        if numel(idxLeg)<10

            valAcc.Text='– %';

            valAcc.FontColor=...
                [0.92 0.95 0.97];

            return;
        end

        leg=...
            state.legV(idxLeg);

        motor=...
            state.motorV(idxMotor);

        valid=...
            isfinite(leg) & ...
            isfinite(motor);

        if nnz(valid)<10

            valAcc.Text='– %';

            valAcc.FontColor=...
                [0.92 0.95 0.97];

            return;
        end

        leg=leg(valid);
        motor=motor(valid);

        mae=...
            mean(...
                abs(...
                    motor-leg));

        rom=...
            max(leg)-...
            min(leg);

        scaleDeg=max(...
            rom,...
            ACCURACY_MIN_SCALE_DEG);

        accuracy=max(...
            0,...
            min(...
                100,...
                100*...
                (1-mae/scaleDeg)));

        valAcc.Text=...
            sprintf(...
                '%.1f %%',...
                accuracy);

        if accuracy>=90

            valAcc.FontColor=...
                [0.25 0.75 0.45];

        elseif accuracy>=75

            valAcc.FontColor=...
                [0.95 0.76 0.30];

        else

            valAcc.FontColor=...
                [0.92 0.34 0.34];
        end
    end

