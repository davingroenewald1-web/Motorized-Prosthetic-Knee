                'Connect system';

            btnLeader.BackgroundColor=...
                [0.94 0.94 0.94];

            setStatus("Disconnected.");
        end
    end

%% WebSocket frame parser

    function parseWebSocketBytes(newBytes)

        state.wsBuffer=[...
            state.wsBuffer,...
            reshape(...
                uint8(newBytes),...
                1,...
                [])];

        while true

            b=state.wsBuffer;

            if numel(b)<2
                return;
            end

            b1=b(1);
            b2=b(2);

            fin=...
                bitand(...
                    b1,...
                    uint8(128))~=0;

            opcode=...
                bitand(...
                    b1,...
                    uint8(15));

            masked=...
                bitand(...
                    b2,...
                    uint8(128))~=0;

            lenCode=double(...
                bitand(...
                    b2,...
                    uint8(127)));

            idx=3;

            if lenCode<=125

                payloadLen=lenCode;

            elseif lenCode==126

                if numel(b)<4
                    return;
                end

                payloadLen=...
                    double(b(3))*256+...
                    double(b(4));

                idx=5;

            else

                if numel(b)<10
                    return;
                end

                payloadLen64=uint64(0);

                for jj=3:10

                    payloadLen64=...
                        bitshift(...
                            payloadLen64,...
                            8)+...
                        uint64(b(jj));
                end

                if payloadLen64>...
                        uint64(1e7)

                    disconnectLeader(true);
                    return;
                end

                payloadLen=...
                    double(payloadLen64);

                idx=11;
            end

            maskKey=uint8([]);

            if masked

                if numel(b)<idx+3
                    return;
                end

                maskKey=b(idx:idx+3);

                idx=idx+4;
            end

            finalIndex=...
                idx+payloadLen-1;

            if numel(b)<finalIndex
                return;
            end

            if payloadLen>0

                payload=...
                    b(idx:finalIndex);

            else

                payload=uint8([]);
            end

            state.wsBuffer=...
                b(finalIndex+1:end);

            if masked && ...
               ~isempty(payload)

                for kk=1:numel(payload)

                    payload(kk)=...
                        bitxor(...
                            payload(kk),...
                            maskKey(...
                                mod(kk-1,4)+1));
                end
            end

            % Close
            if opcode==8

                disconnectLeader(true);
                return;

            % Ping
            elseif opcode==9

                sendWebSocketFrame(...
                    uint8(10),...
                    payload);

                continue;

            % Pong
            elseif opcode==10

                continue;
            end

            % Text frame
            if opcode==1

                if fin

                    handleSystemText(...
                        payload);

                else

                    state.wsFragment=...
                        payload;

                    state.wsFragmentOpcode=...
                        opcode;
                end

            % Continuation frame
            elseif opcode==0

                state.wsFragment=[...
                    state.wsFragment,...
                    payload];

                if fin

                    if state.wsFragmentOpcode==1

                        handleSystemText(...
                            state.wsFragment);
                    end

                    state.wsFragment=uint8([]);
                    state.wsFragmentOpcode=uint8(0);
                end
            end
        end
    end

    function sendWebSocketFrame(...
            opcode,...
            payload)

        if isempty(state.ws)
            return;
        end

        payload=reshape(...
            uint8(payload),...
            1,...
            []);

        payloadLen=numel(payload);

        firstByte=...
            bitor(...
                uint8(128),...
                uint8(opcode));

        maskBit=uint8(128);

        if payloadLen<=125

            header=uint8([...
                firstByte,...
                bitor(...
                    maskBit,...
                    uint8(payloadLen))]);

        elseif payloadLen<=65535

            n16=uint16(payloadLen);

            header=uint8([...
                firstByte,...
                bitor(...
                    maskBit,...
                    uint8(126)),...
                bitand(...
                    bitshift(n16,-8),...
                    255),...
                bitand(...
                    n16,...
                    255)]);

        else

            len64=uint64(payloadLen);

            lenBytes=zeros(...
                1,...
                8,...
                'uint8');

            for jj=8:-1:1

                lenBytes(jj)=...
                    uint8(...
                        bitand(...
                            len64,...
                            uint64(255)));

                len64=...
                    bitshift(...
                        len64,...
                        -8);
            end

            header=[...
                firstByte,...
                bitor(...
                    maskBit,...
                    uint8(127)),...
                lenBytes];
        end

        maskKey=uint8(...
            randi(...
                [0 255],...
                1,...
                4));

        maskedPayload=payload;

        for kk=1:payloadLen

            maskedPayload(kk)=...
                bitxor(...
                    payload(kk),...
                    maskKey(...
                        mod(kk-1,4)+1));
        end

        write(...
            state.ws,...
            [header maskKey maskedPayload],...
            'uint8');
    end

%% Incoming WebSocket text

    function handleSystemText(payload)

        try

            txt=strtrim(...
                string(...
                    native2unicode(...
                        uint8(payload),...
                        'UTF-8')));

        catch
            return;
        end

        if strlength(txt)==0
            return;
        end

        [ok,...
         leaderDeg,...
         motorDeg,...
         hasMotor]=...
            decodeSystemMessage(txt);

        if ok

            onTelemetrySample(...
                leaderDeg,...
                motorDeg,...
                hasMotor);
        end
    end

%% Packet decoder

    function [ok,...
              leaderDeg,...
              motorDeg,...
              hasMotor]=...
              decodeSystemMessage(txt)

        ok=false;
        leaderDeg=NaN;
        motorDeg=NaN;
        hasMotor=false;

        txt=strtrim(...
            string(txt));

        if strlength(txt)==0
            return;
        end

        parts=split(...
            txt,...
            ",");

        % =====================================================
        % CURRENT ESP32 FORMAT
        %
        % L,37.52,M,35.91
        %
        % L,37.52,M,nan
        % =====================================================

        if numel(parts)>=4 && ...
           strcmpi(...
                strtrim(parts(1)),...
                "L") && ...
           strcmpi(...
                strtrim(parts(3)),...
                "M")

            leaderDeg=...
                str2double(...
                    strtrim(parts(2)));

            motorDeg=...
                str2double(...
                    strtrim(parts(4)));

            if ~isfinite(leaderDeg)
                return;
            end

            if leaderDeg<0 || ...
               leaderDeg>120

                return;
            end

            ok=true;

            if isfinite(motorDeg) && ...
               motorDeg>=0 && ...
               motorDeg<=180

                hasMotor=true;

            else

                motorDeg=NaN;
                hasMotor=false;
            end

            return;
        end

        % =====================================================
        % OLD D FORMAT
        %
        % D,37.52,35.91
        % =====================================================

        if numel(parts)>=3 && ...
           strcmpi(...
                strtrim(parts(1)),...
                "D")

            leaderDeg=...
                str2double(...
                    strtrim(parts(2)));

            motorDeg=...
                str2double(...
                    strtrim(parts(3)));

            if ~isfinite(leaderDeg)
                return;
            end

            ok=true;

            hasMotor=...
                isfinite(motorDeg);

            return;
        end

        % =====================================================
        % JSON FORMAT SUPPORT
        % =====================================================

        c=char(txt);

        if ~isempty(c) && ...
           c(1)=='{'

            try

                j=jsondecode(c);

                if isfield(j,'leader')

                    leaderDeg=...
                        double(j.leader);

                elseif isfield(j,'angle')

                    leaderDeg=...
                        double(j.angle);

                elseif isfield(j,'angle_deg')

                    leaderDeg=...
                        double(j.angle_deg);

                else

                    return;
                end

                if isfield(j,'motor')

                    motorDeg=...
                        double(j.motor);

                elseif isfield(...
                        j,...
                        'motor_angle')

                    motorDeg=...
                        double(...
                            j.motor_angle);
                end

                ok=...
                    isfinite(leaderDeg);

                hasMotor=...
                    isfinite(motorDeg);

                return;

            catch
                return;
            end
        end

        % =====================================================
        % LEGACY SINGLE NUMBER
        %
        % 37.52
        % =====================================================

        leaderDeg=...
            str2double(txt);

        if isfinite(leaderDeg)

            ok=true;
            hasMotor=false;
        end
    end

%% Incoming telemetry

    function onTelemetrySample(...
            leaderDeg,...
            motorDeg,...
            hasMotor)

        t=elapsedTime();

        state.legAngle=leaderDeg;

        state.legT(end+1)=t;
        state.legV(end+1)=leaderDeg;

        if hasMotor && ...
           isfinite(motorDeg)

            state.motorAngle=...
                motorDeg;

            state.motorT(end+1)=t;
            state.motorV(end+1)=motorDeg;

        else

            state.motorAngle=NaN;
        end

        processAngleGait(...
            t,...
            leaderDeg);

        trimHistory();
    end

%% Gait detection

    function processAngleGait(...
            t,...
            angleDeg)

        n=min(...
            ANGLE_SMOOTH_N,...
            numel(state.legV));

        smoothAngle=mean(...
            state.legV(...
                end-n+1:end));

        state.angleSmoothT(end+1)=t;
        state.angleSmoothV(end+1)=smoothAngle;

        if ~isfinite(...
                state.prevSmoothAngle)

            state.prevSmoothAngle=...
                smoothAngle;

            state.lastMovementT=t;
        end

        delta=abs(...
            smoothAngle-...
            state.prevSmoothAngle);

        if delta>=MOTION_EPS_DEG
            state.lastMovementT=t;
        end

        state.prevSmoothAngle=...
            smoothAngle;

        % Remember latest extension position
        if smoothAngle<=...
                EXTENSION_REFERENCE_DEG

            state.lastExtensionT=t;
            state.lastExtensionV=smoothAngle;
        end

        % End walking bout
        if state.walkingActive && ...
           isfinite(state.lastMovementT) && ...
           (t-state.lastMovementT)>=IDLE_RESET_S && ...
           smoothAngle<=IDLE_EXTENSION_MAX_DEG

            state.walkingActive=false;
            state.cycleStartT=NaN;
            state.flexionArmed=false;
            state.detectionMode="READY";

            gaitLiveLegLine.XData=NaN;
            gaitLiveLegLine.YData=NaN;

            gaitLiveMotorLine.XData=NaN;
            gaitLiveMotorLine.YData=NaN;

            setStatus(...
                "Standing detected — ready for next walk.");

            return;
        end

        % Start walking bout
        if ~state.walkingActive

            state.detectionMode="READY";

            if smoothAngle>=...
                    START_FLEXION_DEG

                if isfinite(...
                        state.lastExtensionT) && ...
                   (t-state.lastExtensionT)<=...
                        START_LOOKBACK_S

                    state.cycleStartT=...
                        state.lastExtensionT;

                else

                    state.cycleStartT=t;
                end

                state.walkingActive=true;

                state.flexionArmed=...
                    smoothAngle>=...
                    ARM_FLEXION_DEG;

                state.lastMovementT=t;
                state.detectionMode="LIVE";

                setStatus(...
                    "Walking detected — plotting gait live.");
            end

            return;
        end

        state.detectionMode="LIVE";

        if smoothAngle>=ARM_FLEXION_DEG
            state.flexionArmed=true;
        end

        if state.flexionArmed && ...
           smoothAngle<=END_EXTENSION_DEG && ...
           isfinite(state.cycleStartT)

            tEnd=t;

            duration=...
                tEnd-...
                state.cycleStartT;

            if duration>=MIN_CYCLE_S && ...
               duration<=MAX_CYCLE_S

                accepted=...
                    finalizeCycle(...
                        state.cycleStartT,...
                        tEnd);

                if accepted

                    state.cycleDurations(end+1)=...
                        duration;

                    if numel(...
                        state.cycleDurations)>20

                        state.cycleDurations=...
                            state.cycleDurations(...
                                end-19:end);
                    end

                    state.cycleCountTotal=...
                        state.cycleCountTotal+1;

                    state.heelT(end+1)=...
                        tEnd;

                    setStatus(...
                        sprintf(...
                            'Gait cycle %d captured — %.2f s',...
                            state.cycleCountTotal,...
                            duration));
                end

                state.cycleStartT=tEnd;
                state.flexionArmed=false;

            elseif duration>MAX_CYCLE_S

                state.cycleStartT=tEnd;
                state.flexionArmed=false;

                setStatus(...
                    "Gait timing restarted.");
            end
        end
    end

%% Completed cycle processing

    function accepted=...
            finalizeCycle(...
                t0,...
                t1)

        accepted=false;

        legCurveRaw=...
            resampleSeries(...
                state.legT,...
                state.legV,...
                t0,...
                t1,...
                GAIT_POINTS);

        if isempty(legCurveRaw)
            return;
        end

        legROM=...
            max(...
                legCurveRaw,...
                [],...
                'omitnan')-...
            min(...
                legCurveRaw,...
                [],...
                'omitnan');

        if ~isfinite(legROM) || ...
           legROM<MIN_CYCLE_ROM_DEG

            return;
        end

        nBase=min(...
            4,...
            numel(legCurveRaw));

        legBaseline=mean(...
            legCurveRaw(1:nBase),...
            'omitnan');

        legCurve=...
            legCurveRaw-...
            legBaseline;

        motorCurveRaw=...
            resampleSeries(...
                state.motorT,...
                state.motorV,...
                t0,...
                t1,...
                GAIT_POINTS);

        if isempty(motorCurveRaw)

            motorCurve=[];

        else

            nMotorBase=min(...
                4,...
                numel(motorCurveRaw));

            motorBaseline=mean(...
                motorCurveRaw(...
                    1:nMotorBase),...
                'omitnan');

            motorCurve=...
                motorCurveRaw-...
                motorBaseline;
        end

        c=struct(...
            'leg',legCurve,...
            'motor',motorCurve,...
            't0',t0,...
            't1',t1);

        state.cycles(end+1)=c;

        if numel(state.cycles)>...
                MAX_CYCLES

            state.cycles=...
                state.cycles(...
                    end-MAX_CYCLES+1:end);
        end

        accepted=true;
    end

    function curve=...
            resampleSeries(...
                t,...
                v,...
                t0,...
                t1,...
                n)

        curve=[];

        if numel(t)<2
            return;
        end

        mask=...
            t>=t0 & ...
            t<=t1;

        tt=t(mask);
        vv=v(mask);

        if numel(tt)<2
            return;
        end

        [tt,idx]=...
            unique(...
                tt,...
                'stable');

        vv=vv(idx);

        if numel(tt)<2
            return;
        end

        tq=...
            linspace(...
                t0,...
                t1,...
                n);

        try

            curve=interp1(...
                tt,...
                vv,...
                tq,...
                'linear',...
                NaN);

            if nnz(...
                isfinite(curve))<...
                round(0.70*n)

                curve=[];
                return;
            end

            curve=...
                fillmissing(...
                    curve,...
                    'nearest');

        catch

            curve=[];
        end
    end

